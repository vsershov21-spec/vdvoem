package assistant

import "testing"

func TestFixTypos(t *testing.T) {
	for in, want := range map[string]string{
		"что сегондя в кино?":         "что сегодня в кино?",
		"Седня куда сходить":          "сегодня куда сходить",
		"на выхах куда":               "на выходных куда",
		"зафтра вечером":              "завтра вечером",
		"в суботу кинчик":             "в субботу кинчик",
		"грузинские рестики":          "грузинские рестораны",
		"сегодня в кино":              "сегодня в кино",
		"что на выхи":                 "что на выходные",
		"концерт послезавтра":         "концерт послезавтра",
	} {
		if got := fixTypos(in); got != want {
			t.Errorf("%q → %q, want %q", in, got, want)
		}
	}
}
