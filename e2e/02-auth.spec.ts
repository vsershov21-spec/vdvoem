import { test, expect } from '@playwright/test'
import { people, say, press, waitMsg, pair, open, phone, shot, tab, api, BASE } from './lib'

test('E06 интро: лампа зажигается сама, частицы, главная; тап пропускает', async ({ browser }) => {
  const [v, n] = people('Вова', 'Настя')
  await pair(v, n)
  const ctx = await phone(browser)
  const p = await open(ctx, v, '', true)
  await expect(p.locator('.room')).toBeVisible()
  await expect(p.locator('.room[data-on]')).toBeVisible({ timeout: 3000 }) // nobody pulled the cord
  await shot(p, 'E06-lamp-on')
  await expect(p.locator('.intro')).toBeVisible({ timeout: 5000 })
  await p.waitForTimeout(1500)
  await shot(p, 'E06-particles')
  await expect(p.locator('.pnav')).toBeVisible({ timeout: 15000 })
  await expect(p.locator('.room')).toHaveCount(0)
  // second launch the same day: short version, and a tap skips it
  const p2 = await open(ctx, v, '', true)
  await expect(p2.locator('.intro')).toBeVisible({ timeout: 5000 })
  await p2.locator('.room').click()
  await expect(p2.locator('.pnav')).toBeVisible({ timeout: 3000 })
})

test('E03 вход в браузере через Telegram: код одноразовый', async ({ browser }) => {
  const [v, n] = people('Вова', 'Настя')
  await pair(v, n)
  const ctx = await phone(browser)
  const p = await open(ctx, null)
  await expect(p.getByText('С возвращением')).toBeVisible({ timeout: 8000 })
  await shot(p, 'E03-login')
  const [res] = await Promise.all([p.waitForResponse(r => r.url().endsWith('/api/auth/telegram') && r.request().method() === 'POST'), p.getByRole('button', { name: 'Войти через Telegram' }).click()])
  const { code } = await res.json()
  await expect(p.getByText('Подтверди вход в боте')).toBeVisible()
  await say(v, '/start login_' + code)
  await waitMsg(v, /Войти во «Вдвоём» в браузере\?/)
  await press(v, 'Да, это я')
  await expect(p.locator('.pnav')).toBeVisible({ timeout: 10000 })
  await expect(p.getByText(/Добрый|Доброе|Доброй/)).toContainText('Вова')
  await shot(p, 'E03-in')
  const again = await (await fetch(`${BASE}/api/auth/telegram/${code}`)).json()
  expect(again.ok).toBe(false)
})

test('E04 логин и пароль: вход, ошибка, блокировка', async ({ browser }) => {
  const [v, n] = people('Вова', 'Настя')
  await pair(v, n)
  const login = 'vova' + v.id
  await expect(api(v, 'POST', '/security/password', { login, password: 'short' })).rejects.toThrow(/weak_password/)
  await api(v, 'POST', '/security/password', { login, password: 'correct horse' })
  const ctx = await phone(browser)
  const p = await open(ctx, null)
  await p.getByRole('tab', { name: 'Пароль' }).click()
  await p.getByPlaceholder('Логин').fill(login)
  await p.getByPlaceholder('Пароль').fill('wrong pass')
  await p.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(p.getByRole('alert')).toContainText('Неверный логин или пароль')
  await shot(p, 'E04-wrong')
  await p.getByPlaceholder('Пароль').fill('correct horse')
  await p.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(p.locator('.pnav')).toBeVisible({ timeout: 10000 })
  // the session is listed in «Мы → Безопасность»
  await tab(p, 'us')
  await expect(p.getByText('это устройство')).toBeVisible()
  // lockout after five wrong attempts
  for (let k = 0; k < 5; k++) await fetch(BASE + '/api/auth/password', { method: 'POST', body: JSON.stringify({ login, password: 'nope' }) })
  const r = await fetch(BASE + '/api/auth/password', { method: 'POST', body: JSON.stringify({ login, password: 'correct horse' }) })
  expect(r.status).toBe(429)
})

test('E05 Face ID (passkey): добавить, выйти, войти', async ({ browser }) => {
  const [v, n] = people('Вова', 'Настя')
  await pair(v, n)
  const login = 'face' + v.id
  await api(v, 'POST', '/security/password', { login, password: 'correct horse' })
  const ctx = await phone(browser)
  const p = await open(ctx, null)
  const cdp = await ctx.newCDPSession(p)
  await cdp.send('WebAuthn.enable')
  await cdp.send('WebAuthn.addVirtualAuthenticator', { options: { protocol: 'ctap2', transport: 'internal', hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } })
  await p.getByRole('tab', { name: 'Пароль' }).click()
  await p.getByPlaceholder('Логин').fill(login)
  await p.getByPlaceholder('Пароль').fill('correct horse')
  await p.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(p.locator('.pnav')).toBeVisible({ timeout: 10000 })
  await tab(p, 'us')
  await p.getByRole('button', { name: /Face ID для браузера/ }).click()
  await expect(p.getByText('Face ID добавлен')).toBeVisible({ timeout: 10000 })
  await shot(p, 'E05-added')
  const sec = await api(v, 'GET', '/security')
  expect(sec.passkeys.length).toBe(1)
  await p.getByRole('button', { name: 'Выйти', exact: true }).click()
  await expect(p.getByText('С возвращением')).toBeVisible({ timeout: 10000 })
  await p.getByRole('tab', { name: 'Face ID' }).click()
  await p.getByRole('button', { name: 'Войти с Face ID' }).click()
  await expect(p.locator('.pnav')).toBeVisible({ timeout: 10000 })
  await shot(p, 'E05-in')
})
