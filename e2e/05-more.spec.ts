import { test, expect } from '@playwright/test'
import { people, pair, open, phone, shot, tab, api, addIdeas, planMeeting } from './lib'

test('E17 «Удиви нас» в приложении: «Давай!» открывает выбор с готовой идеей', async ({ browser }) => {
  const [v, n] = people('Вова', 'Настя')
  await pair(v, n)
  await addIdeas(v, ['Ужин в ресторане', 'Музей', 'Каток'])
  const p = await open(await phone(browser), v)
  await p.getByRole('button', { name: 'Удиви нас' }).first().click()
  await expect(p.getByText('Случайно из копилки')).toBeVisible({ timeout: 8000 })
  await shot(p, 'E17-surprise')
  await p.getByRole('button', { name: 'Другую' }).click()
  await expect(p.getByText('Мой совет')).toBeVisible({ timeout: 8000 })
  await p.getByRole('button', { name: 'Давай!' }).click()
  await expect(p.getByText('Решили')).toBeVisible()
  await expect(p.getByText('Когда удобно')).toBeVisible()
  // the Dynamic Island now shows the live round and its quick actions
  await p.goto('/app/')
  await expect(p.getByTestId('island')).toContainText('шаг 1/3')
  await p.getByTestId('island').click()
  await expect(p.getByRole('button', { name: 'Добавить идею' }).first()).toBeVisible()
  await shot(p, 'E17-island')
})

test('E18 помощник: ответы, карточки, кнопки срабатывают один раз и только нажатием', async ({ browser }) => {
  const [v, n] = people('Вова', 'Настя')
  await pair(v, n)
  await addIdeas(v, ['Ужин в ресторане', 'Музей космонавтики'])
  const p = await open(await phone(browser), v)
  await tab(p, 'ai')
  await expect(p.getByText('Чем помочь?')).toBeVisible()
  await shot(p, 'E18-empty')
  await p.getByRole('button', { name: 'Куда сходить в субботу вечером?' }).click()
  await expect(p.locator('.ai-card').first()).toBeVisible({ timeout: 10000 })
  await p.getByPlaceholder(/Спроси/).fill('добавь: каток в Парке Горького')
  await p.getByLabel('Отправить').click()
  await expect(p.locator('.ai-act', { hasText: 'Добавить' })).toBeVisible()
  expect((await api(v, 'GET', '/ideas')).ideas.some((i: any) => /каток/i.test(i.title))).toBe(false)
  await shot(p, 'E18-chat')
  await p.locator('.ai-act', { hasText: 'Добавить' }).click()
  await expect(p.locator('.ai-act[data-done]')).toBeVisible()
  await expect.poll(async () => (await api(v, 'GET', '/ideas')).ideas.some((i: any) => /каток/i.test(i.title))).toBe(true)
  await p.locator('.ai-act', { hasText: /Идём/ }).first().click()
  await expect.poll(async () => !!(await api(v, 'GET', '/rounds/current')).round).toBe(true)
  await p.getByPlaceholder(/Спроси/).fill('что у нас запланировано?')
  await p.getByLabel('Отправить').click()
  await expect(p.locator('.msg--ai').last()).toContainText(/Идёт выбор|Ближайшая встреча|Ничего/)
})

test('E19 календарь: встречи и дедлайны на днях, выбор на конкретный день', async ({ browser }) => {
  const [v, n] = people('Вова', 'Настя')
  await pair(v, n)
  await addIdeas(v, ['Ужин в ресторане', 'Кино', 'Купить продукты'])
  const planned = await planMeeting(v, n)
  const chore = (await api(v, 'GET', '/ideas?kind=chore')).ideas[0]
  const dl = Math.floor(Date.now() / 1000) + 3 * 86400
  await api(v, 'PATCH', '/ideas/' + chore.id, { deadline: dl })
  const p = await open(await phone(browser), v)
  await tab(p, 'cal')
  const day = new Date(planned.starts_at * 1000)
  if (day.getMonth() !== new Date().getMonth()) await p.getByLabel('Следующий месяц').click()
  await expect(p.locator('.mcal__day.is-planned')).toHaveCount(1)
  await expect(p.locator('.sched__row', { hasText: planned.chosen.title })).toBeVisible()
  await shot(p, 'E19-calendar')
  await p.locator('.mcal__day.is-planned').click()
  await expect(p.locator('.sched__row')).toHaveCount(1)
  await p.locator('.sched__row').click()
  await expect(p.getByRole('button', { name: 'В календарь' })).toBeVisible()
  // a free future day → a round on that day (after the planned one is cancelled)
  await api(v, 'POST', `/rounds/${planned.id}/cancel`)
  await p.goto('/app/calendar')
  const free = p.locator('.mcal__day:not(.is-past):not(.is-planned):not(.is-today)').last()
  const date = await free.getAttribute('aria-label')
  await free.click()
  await p.getByRole('button', { name: 'Выбрать вместе на этот день' }).click()
  await expect(p.getByText('Когда удобно')).toBeVisible()
  const cur = (await api(v, 'GET', '/rounds/current')).round
  expect(cur.days[0]).toBe(date)
})

test('E20 настройки: режим предложений, бюджет отсекает дорогие идеи', async ({ browser }) => {
  const [v, n] = people('Вова', 'Настя')
  await pair(v, n)
  const [cheap, pricey] = await addIdeas(v, ['Кофе на набережной', 'Ужин в «Белуге»'])
  await api(v, 'PATCH', '/ideas/' + cheap, { price_min: 100000, price_max: 100000 })
  await api(v, 'PATCH', '/ideas/' + pricey, { price_min: 2000000, price_max: 2000000 })
  await api(n, 'POST', `/ideas/${pricey}/wish`, { wish: 'very' })
  const p = await open(await phone(browser), v)
  await tab(p, 'us')
  await p.getByText('Бот сам предлагает идеи').click()
  await p.getByText('Рандом', { exact: true }).click()
  await expect.poll(async () => (await api(v, 'GET', '/settings')).suggest_mode).toBe('random')
  await shot(p, 'E20-suggest')
  await p.keyboard.press('Escape')
  await p.locator('.scrim').click()
  await p.getByText('Бюджет на встречу').click()
  await p.locator('.sheet .input').fill('5000')
  await p.getByRole('button', { name: 'Сохранить' }).click()
  await expect.poll(async () => (await api(v, 'GET', '/settings')).budget).toBe(500000)
  for (let k = 0; k < 4; k++) expect((await api(v, 'GET', '/suggest?mode=random')).idea.id).toBe(cheap)
})

test('E22 тема и анимации: тёмная тема, reduced-motion, переключатель темы', async ({ browser }) => {
  const [v, n] = people('Вова', 'Настя')
  await pair(v, n)
  await addIdeas(v, ['Ужин в ресторане'])
  const ctx = await phone(browser, { dark: true, reduced: true })
  const p = await open(ctx, v, '', true)
  await expect(p.locator('.pnav')).toBeVisible({ timeout: 8000 })
  expect(await p.evaluate(() => document.documentElement.dataset.theme)).toBe('dark')
  await shot(p, 'E22-dark')
  await tab(p, 'us')
  await p.getByRole('tab', { name: 'Светлая' }).click()
  expect(await p.evaluate(() => document.documentElement.dataset.theme)).toBe('light')
  await expect.poll(async () => (await api(v, 'GET', '/security')).theme).toBe('light')
})
